"""mk_sync.py: S3M 'W' (= MIDAS sync) commands of AUMAX.S3M -> web/fx/sync.js  [[order,row,info],...]  (info 0x10-0x13 are the brightness flashes of the sync callback 0x100910)"""
import struct
d=open('AUMAX.S3M','rb').read()
n,ni,npat=struct.unpack('<HHH',d[0x20:0x26]); orders=list(d[0x60:0x60+n])
pp=[struct.unpack('<H',d[0x60+n+2*ni+2*i:][:2])[0]*16 for i in range(npat)]
ev=[]
for oi,p in enumerate(orders):
    if p>=npat: continue
    o=pp[p]+2
    for r in range(64):
        while True:
            b=d[o]; o+=1
            if b==0: break
            if b&32: o+=2
            if b&64: o+=1
            if b&128:
                c,i=d[o],d[o+1]; o+=2
                if c==23: ev.append([oi,r,i])
open('web/fx/sync.js','w').write('// generated by re/mk_sync.py: [order,row,info] of every S3M Wxx (MIDAS sync) command in AUMAX.S3M\nexport const SYNC = '+str(ev).replace(' ','')+';\n')
print(len(ev),{i for _,_,i in ev})
